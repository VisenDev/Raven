"""Common Lisp: portable, low-level CFFI declarations."""

from cparse import classify, doc_lines


def symbol(name):
    return name.lower()


def string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def packed(head, items, indent="  ", closing=")"):
    """Pack complete Lisp expressions while reserving space for closing parens."""
    lines = [head]
    for item in items:
        if len(lines[-1]) + 1 + len(item) + len(closing) <= 78:
            lines[-1] += " " + item
        else:
            lines.append(indent + item)
    lines[-1] += closing
    return lines


def foreign_type(ctype, api):
    kind, detail = classify(ctype, api)
    if kind == "void":
        return ":void"
    if kind == "scalar":
        return {"int": ":int", "float": ":float", "double": ":double",
                "char": ":char", "size_t": ":size", "uintptr": ":uintptr",
                "uint64": ":uint64", "uint32": ":uint32", "uint8": ":uint8",
                "id": ":uint32"}[detail]
    if kind in ("enum", "callback"):
        return symbol(detail)
    if kind == "struct":
        return "(:struct %s)" % symbol(detail)
    # Strings too: retain NULL, ownership, and explicit byte lengths.
    return ":pointer"


def generate(api):
    exports = ["load-library", "rid", "ruint"]
    exports += [symbol(n) for n, _, _ in api.defines]
    for enum in api.enums:
        exports.append(symbol(enum.name))
        exports.extend(symbol(n) for n, _, _ in enum.items)
    for struct in api.structs:
        exports.append(symbol(struct.name))
        exports.extend(symbol(f.name) for f in struct.fields)
    for callback in api.callbacks:
        exports.extend((symbol(callback.name), "define-" + symbol(callback.name)))
    exports.extend(symbol(f.name) for f in api.functions)
    # Do not inherit CL symbols: C field names may include TYPE or other CL names.
    package = ["(defpackage #:raven", "  (:use)", "  (:export"]
    package[2:] = packed("  (:export",
                         ["#:" + name for name in sorted(set(exports))],
                         indent="   ", closing="))")
    out = [";;; Generated by tools/bindgen; do not edit. Raven " + api.version,
           '(in-package #:raven)', '']
    w = out.append
    w('(cffi:define-foreign-library raven-library')
    w('  (:windows "raven.dll")')
    w('  (:darwin "libraven.dylib")')
    w('  (:unix "libraven.so")')
    w('  (cl:t (:default "raven")))')
    w('')
    w('(cl:defun load-library (cl:&optional path)')
    w('  "Load Raven from PATH, RAVEN_LIBRARY, or the system library search path."')
    w('  (cl:let ((path (cl:or path (uiop:getenv "RAVEN_LIBRARY"))))')
    w('    (cl:if path')
    w('           (cffi:load-foreign-library path)')
    w("           (cffi:use-foreign-library raven-library))))")
    w('')
    w('(cffi:defctype rid :uint32)')
    w('(cffi:defctype ruint :uint32)')
    for name, kind, value in api.defines:
        # String constants cannot portably be redefined with DEFCONSTANT.
        form = 'cl:defparameter' if kind == 'str' else 'cl:defconstant'
        w('(%s %s %s)' % (form, symbol(name),
                           string(value) if kind == 'str' else value))
    for enum in api.enums:
        w('')
        w('(cffi:defctype %s :int)' % symbol(enum.name))
        for name, value, doc in enum.items:
            w('(cl:defconstant %s %d)' % (symbol(name), value))
    for callback in api.callbacks:
        w('(cffi:defctype %s :pointer)' % symbol(callback.name))
    for struct in api.structs:
        w('')
        for line in doc_lines(struct.doc):
            w((';; ' + line).rstrip())
        w('(cffi:defcstruct %s' % symbol(struct.name))
        for field in struct.fields:
            w('  (%s %s%s)' % (symbol(field.name),
                               foreign_type(field.ctype, api),
                               ' :count %d' % field.array if field.array else ''))
        out[-1] += ')'
    for callback in api.callbacks:
        w('')
        for line in doc_lines(callback.doc):
            w((';; ' + line).rstrip())
        out.extend(packed('(cl:defmacro define-%s' % symbol(callback.name),
                          ['(name arguments cl:&body body)'], closing=''))
        w('  "Define a C callback; ARGUMENTS supplies one Lisp name per C parameter."')
        args = ['a%d' % i for i in range(len(callback.params))]
        w('  (cl:destructuring-bind (%s) arguments' % ' '.join(args))
        w('    `(cffi:defcallback ,name %s' % foreign_type(callback.ret, api))
        out.extend(packed('         (',
                          ['(,%s %s)' % (arg, foreign_type(p.ctype, api))
                           for arg, p in zip(args, callback.params)],
                          indent='          '))
        w('       ,@body)))')
    for function in api.functions:
        w('')
        for line in doc_lines(function.doc):
            w((';; ' + line).rstrip())
        out.extend(packed(
            '(cffi:defcfun (%s %s)' %
            (string(function.name), symbol(function.name)),
            [foreign_type(function.ret, api)] +
            ['(arg-%s %s)' % (symbol(p.name), foreign_type(p.ctype, api))
             for p in function.params]))

    return {
        'common-lisp/raven.asd': ''';;; Generated by tools/bindgen; do not edit.
(defsystem "raven"
  :description "Common Lisp CFFI bindings for Raven"
  :depends-on ("cffi")
  :serial t
  :components ((:file "package") (:file "raven")))
''',
        'common-lisp/package.lisp': '\n'.join(package) + '\n',
        'common-lisp/raven.lisp': '\n'.join(out) + '\n',
    }
